-- 1) Tabla de responsables (varios por compuerta; los celulares abren tel:)
create table if not exists public.compuertas_contactos (
    id           bigint generated by default as identity primary key,
    compuerta_id bigint not null references public.compuertas(id) on delete cascade,
    nombre       text   not null,
    cargo        text,
    telefono     text   not null,
    creado_en    timestamptz not null default now()
);

create index if not exists compuertas_contactos_compuerta_idx
    on public.compuertas_contactos (compuerta_id);

-- 2) Permisos de tabla para la clave publica (misma politica que el resto de la app)
grant select, insert, update, delete on public.compuertas_contactos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 3) RLS de la tabla nueva
alter table public.compuertas_contactos enable row level security;

drop policy if exists "compuertas_contactos_lectura"  on public.compuertas_contactos;
drop policy if exists "compuertas_contactos_alta"     on public.compuertas_contactos;
drop policy if exists "compuertas_contactos_cambio"   on public.compuertas_contactos;
drop policy if exists "compuertas_contactos_borrado"  on public.compuertas_contactos;

create policy "compuertas_contactos_lectura" on public.compuertas_contactos
    for select to anon, authenticated using (true);
create policy "compuertas_contactos_alta" on public.compuertas_contactos
    for insert to anon, authenticated with check (true);
create policy "compuertas_contactos_cambio" on public.compuertas_contactos
    for update to anon, authenticated using (true) with check (true);
create policy "compuertas_contactos_borrado" on public.compuertas_contactos
    for delete to anon, authenticated using (true);

-- 4) Permitir crear compuertas nuevas (hoy el INSERT esta bloqueado: error 42501)
drop policy if exists "compuertas_alta" on public.compuertas;
create policy "compuertas_alta" on public.compuertas
    for insert to anon, authenticated with check (true);

-- 5) Permitir quitar compuertas (el borrado arrastra sus responsables por el "on delete cascade")
drop policy if exists "compuertas_borrado" on public.compuertas;
create policy "compuertas_borrado" on public.compuertas
    for delete to anon, authenticated using (true);
