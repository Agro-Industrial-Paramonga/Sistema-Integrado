--
--  Una sola fila viva (id = 1) con el nivel actual; el historial
--  queda en semaforo_eventos (solo alta y lectura: no se borra).
--  Este SQL se puede volver a ejecutar: usa "if not exists" y
--  "drop policy if exists" antes de cada política.
-- ============================================================

-- 1) Estado vigente del semáforo (una fila, siempre la misma)
create table if not exists public.semaforo_estado (
    id                smallint    primary key default 1,
    nivel             text        not null default 'verde',
    motivo            text,
    declarado_por     text,
    declarado_por_rol text,
    es_guardia        boolean     not null default false,
    vigente_desde     timestamptz not null default now(),
    actualizado_en    timestamptz not null default now(),
    constraint semaforo_estado_nivel_valido check (nivel in ('verde', 'amarillo', 'naranja', 'rojo')),
    constraint semaforo_estado_fila_unica  check (id = 1)
);

insert into public.semaforo_estado (id, nivel, vigente_desde, actualizado_en)
values (1, 'verde', now(), now())
on conflict (id) do nothing;

-- 2) Historial de cambios (evidencia para el SGI y el reporte posterior)
create table if not exists public.semaforo_eventos (
    id                bigint generated by default as identity primary key,
    nivel             text        not null,
    nivel_anterior    text,
    motivo            text,
    declarado_por     text,
    declarado_por_rol text,
    es_guardia        boolean     not null default false,
    verificado        boolean     not null default false,
    creado_en         timestamptz not null default now()
);

create index if not exists semaforo_eventos_creado_idx
    on public.semaforo_eventos (creado_en desc);

-- 3) Permisos de tabla para la clave pública (igual que el resto de la app)
grant select, insert, update on public.semaforo_estado to anon, authenticated;
grant select, insert         on public.semaforo_eventos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 4) RLS
alter table public.semaforo_estado  enable row level security;
alter table public.semaforo_eventos enable row level security;

drop policy if exists "semaforo_estado_lectura"  on public.semaforo_estado;
drop policy if exists "semaforo_estado_alta"     on public.semaforo_estado;
drop policy if exists "semaforo_estado_cambio"   on public.semaforo_estado;
drop policy if exists "semaforo_eventos_lectura" on public.semaforo_eventos;
drop policy if exists "semaforo_eventos_alta"    on public.semaforo_eventos;

create policy "semaforo_estado_lectura" on public.semaforo_estado
    for select to anon, authenticated using (true);
create policy "semaforo_estado_alta" on public.semaforo_estado
    for insert to anon, authenticated with check (true);
create policy "semaforo_estado_cambio" on public.semaforo_estado
    for update to anon, authenticated using (true) with check (true);

create policy "semaforo_eventos_lectura" on public.semaforo_eventos
    for select to anon, authenticated using (true);
create policy "semaforo_eventos_alta" on public.semaforo_eventos
    for insert to anon, authenticated with check (true);

-- Nota: no se crean políticas de delete. El historial no se borra desde la app.
-- El control de quién declara cada nivel está en la pantalla (roles del pc_user),
-- igual que el resto de la aplicación.
